"""Canonical pydantic v2 models shared by edge and cloud.

Events, captions, coverage, messages, and site/rule/policy configs live here;
services must not redefine them. See spec/ARCHITECTURE.md §9.

Rules every model follows:

- Timestamps are timezone-aware and normalised to UTC; naive ones are rejected.
- Unknown fields are rejected and instances are immutable.
- Fields marked local-only (e.g. ``Event.media``) never leave the box: use
  ``cloud_dump()`` for anything sent to the cloud.
"""

